#!/bin/bash
# Lightsail first-boot setup for the CodeSampleX host (2GB RAM plan):
# Docker + compose plugin + 2G swap, ready to receive the compose bundle.
set -eux

# Swap first — 2GB RAM needs headroom before anything heavy runs.
if [ ! -f /swapfile ]; then
  fallocate -l 2G /swapfile
  chmod 600 /swapfile
  mkswap /swapfile
  swapon /swapfile
  echo '/swapfile none swap sw 0 0' >> /etc/fstab
  sysctl vm.swappiness=20
  echo 'vm.swappiness=20' > /etc/sysctl.d/90-csx.conf
fi

apt-get update
apt-get install -y ca-certificates curl
install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
chmod a+r /etc/apt/keyrings/docker.asc
echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" > /etc/apt/sources.list.d/docker.list
apt-get update
apt-get install -y docker-ce docker-ce-cli containerd.io docker-compose-plugin
usermod -aG docker ubuntu

mkdir -p /opt/codesamplex
chown ubuntu:ubuntu /opt/codesamplex
